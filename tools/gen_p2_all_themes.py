def extract_palette(theme_id: str) -> str:
    """Prefer standalone theme_palette.c; fall back to existing theme_pack.c."""
    pal_path = THEMES / theme_id / "theme_palette.c"
    pack_path = THEMES / theme_id / "theme_pack.c"
    if pal_path.exists():
        text = pal_path.read_text(encoding="utf-8")
        text = re.sub(r'#include\s+"hub_theme\.h"\s*\n*', "", text)
        return text.strip() + "\n"
    if pack_path.exists():
        text = pack_path.read_text(encoding="utf-8")
        m = re.search(
            r"(static const hub_palette_t s_pal = \{.*?\n\};\n\n"
            r"const hub_palette_t \*hub_palette\(void\)\n\{\n    return &s_pal;\n\}\n)",
            text,
            re.S,
        )
        if not m:
            raise RuntimeError(f"{theme_id}: cannot extract palette from theme_pack.c")
        return m.group(1)
    raise FileNotFoundError(f"{theme_id}: no theme_palette.c or theme_pack.c")


