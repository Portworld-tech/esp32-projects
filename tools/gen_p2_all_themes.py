def upgrade_pages(pages: str) -> str:
    # Settings: add 温控 + 点表 rows
    old_settings = '''    } rows[] = {
        { HUB_ICO_WIFI, "网络与配网", "Wi-Fi / 以太网", HUB_ROUTE_NETWORK },
        { HUB_ICO_SHIELD, "安防", "布防 / 撤防", HUB_ROUTE_SECURITY },
        { HUB_ICO_BUS, "总线", "MQTT / Modbus", HUB_ROUTE_GATEWAY },
        { HUB_ICO_HOME, "房间", "控件布局", HUB_ROUTE_ROOM },
        { HUB_ICO_CLOCK, "日程", "定时与场景", HUB_ROUTE_SCHEDULE },
    };
    for (int i = 0; i < 5; i++) {'''

    new_settings = '''    } rows[] = {
        { HUB_ICO_WIFI, "网络与配网", "Wi-Fi / 以太网", HUB_ROUTE_NETWORK },
        { HUB_ICO_SHIELD, "安防", "布防 / 撤防", HUB_ROUTE_SECURITY },
        { HUB_ICO_BUS, "总线", "MQTT / Modbus", HUB_ROUTE_GATEWAY },
        { HUB_ICO_SNOW, "温控", "空调与地暖", HUB_ROUTE_HVAC },
        { HUB_ICO_LAYERS, "点表", "设备点位", HUB_ROUTE_POINTS },
        { HUB_ICO_HOME, "房间", "控件布局", HUB_ROUTE_ROOM },
        { HUB_ICO_CLOCK, "日程", "定时与场景", HUB_ROUTE_SCHEDULE },
    };
    for (int i = 0; i < 7; i++) {'''

    if old_settings not in pages:
        raise RuntimeError("settings rows block not found")
    pages = pages.replace(old_settings, new_settings)

    # Insert HVAC/POINTS before entry, and extend switch
    marker = "/* ── entry ───────────────────────────────────────────────────────── */"
    if marker not in pages:
        raise RuntimeError("entry marker not found in PAGES")
    pages = pages.replace(marker, HVAC_AND_POINTS.lstrip("\n") + marker)

    old_switch = '''    case HUB_ROUTE_SCHEDULE: build_schedule(parent); break;
    default: build_home(parent); break;'''
    new_switch = '''    case HUB_ROUTE_SCHEDULE: build_schedule(parent); break;
    case HUB_ROUTE_HVAC: build_hvac(parent); break;
    case HUB_ROUTE_POINTS: build_points(parent); break;
    default: build_home(parent); break;'''
    if old_switch not in pages:
        raise RuntimeError("hub_theme_build switch not found")
    pages = pages.replace(old_switch, new_switch)
    return pages


def wrap(theme_id: str, palette: str, home: str, pages: str) -> str:
    name = theme_id.capitalize()
    parts = [
        HEADER.format(name=name),
        "/* ── palette ─────────────────────────────────────────────────────── */\n",
        palette,
        "\n",
        HELPERS.format(),  # double braces already escaped
        "/* ── HOME ────────────────────────────────────────────────────────── */\n",
        home.strip(),
        "\n\n",
        pages.lstrip("\n"),
        "\n",
        BOOT.lstrip("\n"),
    ]
    return "".join(parts)


def verify_pack(path: Path) -> list[str]:
    text = path.read_text(encoding="utf-8")
    missing = []
    for sym in ("hub_palette", "hub_theme_build", "app_ui_start", "build_hvac", "build_points"):
        if sym not in text:
            missing.append(sym)
    return missing


def main() -> None:
    p1 = _load_p1()
    homes = upgrade_homes(dict(p1.HOMES))
    pages = upgrade_pages(p1.PAGES)

    written: list[Path] = []
    issues: list[str] = []

    for tid in THEME_IDS:
        try:
            palette = extract_palette(tid)
        except (FileNotFoundError, RuntimeError) as exc:
            issues.append(str(exc))
            continue
        out = THEMES / tid / "theme_pack.c"
        out.parent.mkdir(parents=True, exist_ok=True)
        text = wrap(tid, palette, homes[tid], pages)
        out.write_text(text, encoding="utf-8", newline="\n")
        written.append(out)
        miss = verify_pack(out)
        if miss:
            issues.append(f"{tid}: missing symbols {miss}")
        print(f"wrote {out} ({len(text.splitlines())} lines)")

    if len(written) != len(THEME_IDS):
        print(f"ERROR: only wrote {len(written)}/{len(THEME_IDS)} packs", file=sys.stderr)
        sys.exit(1)

    # Cleanup old split files after successful generation
    deleted = []
    for tid in THEME_IDS:
        for name in OLD_THEME_FILES:
            p = THEMES / tid / name
            if p.exists():
                p.unlink()
                deleted.append(p)
                print(f"deleted {p}")

    print(f"done: {len(written)} theme_pack.c, deleted {len(deleted)} old files")
    if issues:
        print("ISSUES:")
        for i in issues:
            print(f"  - {i}")
        sys.exit(1)


if __name__ == "__main__":
    main()
