def slice_between(text: str, start_pat: str, end_pat: str | None) -> str:
    sm = re.search(start_pat, text)
    if not sm:
        raise RuntimeError(f"start not found: {start_pat}")
    start = sm.start()
    if end_pat is None:
        return text[start:]
    em = re.search(end_pat, text[sm.end() :])
    if not em:
        raise RuntimeError(f"end not found: {end_pat}")
    return text[start : sm.end() + em.start()]


def destatic(block: str) -> str:
    block = re.sub(r"^static void ", "void ", block, flags=re.M)
    block = re.sub(r"^static char ", "char ", block, flags=re.M)
    block = re.sub(r"^static lv_obj_t \*", "lv_obj_t *", block, flags=re.M)
    return block


def extract_helpers(text: str) -> str:
    block = slice_between(
        text,
        r"/\* ── local helpers.*?\n",
        r"/\* ── HOME",
    )
    # drop the marker line
    block = re.sub(r"^/\* ── local helpers.*\n", "", block)
    block = destatic(block)
    # remove toggle/step if present later — they live in ROOM in packs
    return block.strip() + "\n"


def extract_palette(text: str) -> str:
    m = re.search(
        r"(static const hub_palette_t s_pal = \{.*?\n\};\n\n"
        r"const hub_palette_t \*hub_palette\(void\)\n\{\n    return &s_pal;\n\}\n)",
        text,
        re.S,
    )
    if not m:
        raise RuntimeError("palette extract failed")
    return m.group(1)


def extract_fn_block(text: str, name: str, next_names: tuple[str, ...]) -> str:
    start = re.search(rf"(?:static )?void {name}\(lv_obj_t \*parent\)\s*\n\{{", text)
    if not start:
        raise RuntimeError(f"fn {name} not found")
    rest = text[start.end() :]
    # find matching close by scanning braces from the opening we already consumed
    depth = 1
    i = 0
    while i < len(rest) and depth:
        if rest[i] == "{":
            depth += 1
        elif rest[i] == "}":
            depth -= 1
        i += 1
    body = text[start.start() : start.end() + i]
    return destatic(body)


def extract_until_marker(text: str, start_re: str, end_re: str) -> str:
    sm = re.search(start_re, text)
    if not sm:
        raise RuntimeError(start_re)
    em = re.search(end_re, text[sm.start() + 1 :])
    if not em:
        raise RuntimeError(end_re)
    return destatic(text[sm.start() : sm.start() + 1 + em.start()])


