def polish_pages(block: str) -> str:
    """Insert theme_card_chrome after hub_apply_card in page builders."""
    # Avoid double-insert
    out = []
    for line in block.splitlines(keepends=True):
        out.append(line)
        m = re.match(r"(\s*)hub_apply_card\(([^,]+),\s*([^)]+)\);\s*$", line)
        if m and "theme_card_chrome" not in line:
            indent, obj, act = m.group(1), m.group(2).strip(), m.group(3).strip()
            # skip nested tiny buttons sometimes — still OK to chrome
            out.append(f"{indent}theme_card_chrome({obj}, {act});\n")
    return "".join(out)


def write_theme(tid: str) -> None:
    pack = THEMES / tid / "theme_pack.c"
    if not pack.exists():
        # already split? try reading home.c
        raise FileNotFoundError(pack)
    text = pack.read_text(encoding="utf-8")
    name = tid.capitalize()
    out_dir = THEMES / tid

    palette = extract_palette(text)
    helpers = extract_helpers(text)

    # HOME
    home_m = re.search(r"(?:static )?void build_home\(lv_obj_t \*parent\)\s*\n\{", text)
    if not home_m:
        raise RuntimeError(f"{tid}: build_home missing")
    # extract full function with brace match
    home = extract_fn_block(text, "build_home", ())
    home = patch_home(tid, home)

    # Extract page sections from original for ops/life/scenes — but room is deep rewrite
    scenes = extract_fn_block(text, "build_scenes", ())
    scenes = polish_pages(scenes)

    energy = extract_fn_block(text, "build_energy", ())
    gateway = extract_fn_block(text, "build_gateway", ())
    network = extract_fn_block(text, "build_network", ())
    # points: include point_tap_cb
    pt = re.search(r"(?:static )?void point_tap_cb", text)
    bp = re.search(r"(?:static )?void build_points", text)
    if not pt or not bp:
        raise RuntimeError(f"{tid}: points missing")
    points_block = destatic(text[pt.start() : bp.start()]) + extract_fn_block(text, "build_points", ())
    points_block = polish_pages(points_block)

    settings = extract_fn_block(text, "build_settings", ())
    # security includes pin
    pin = re.search(r"(?:static )?char s_pin_buf", text)
    sec = re.search(r"(?:static )?void build_security", text)
    if not pin or not sec:
        raise RuntimeError(f"{tid}: security missing")
    # from s_pin_buf through end of build_security
    sec_start = pin.start()
    # find build_schedule after security
    sch = re.search(r"(?:static )?void build_schedule", text)
    hvac_m = re.search(r"(?:static )?void build_hvac", text)
    if not sch or not hvac_m:
        raise RuntimeError(f"{tid}: schedule/hvac missing")
    security_block = destatic(text[sec_start : sch.start()])
    schedule = extract_fn_block(text, "build_schedule", ())
    hvac = extract_fn_block(text, "build_hvac", ())

    settings = polish_pages(settings)
    security_block = polish_pages(security_block)
    schedule = polish_pages(schedule)
    hvac = polish_pages(hvac)
    energy = polish_pages(energy)
    gateway = polish_pages(gateway)
    network = polish_pages(network)

    # Files
    (out_dir / "theme_local.h").write_text(LOCAL_H.format(name=name), encoding="utf-8", newline="\n")

    (out_dir / "palette.c").write_text(
        f"/** {name} palette */\n#include \"hub_theme.h\"\n\n{palette}",
        encoding="utf-8",
        newline="\n",
    )

    local_c = (
        f"/** {name} theme-local helpers + chrome */\n"
        + COMMON_INCLUDES
        + "\n"
        + helpers
        + "\n"
        + EXTRA_CBS
        + "\n"
        + CHROME[tid].lstrip("\n")
    )
    (out_dir / "theme_local.c").write_text(local_c, encoding="utf-8", newline="\n")

    (out_dir / "home.c").write_text(
        f"/** {name} home */\n{COMMON_INCLUDES}\n{home}\n",
        encoding="utf-8",
        newline="\n",
    )

    (out_dir / "pages_room.c").write_text(
        f"/** {name} room page (deep widgets) */\n{COMMON_INCLUDES}\n{DEEP_ROOM}\n",
        encoding="utf-8",
        newline="\n",
    )

    (out_dir / "pages_scenes.c").write_text(
        f"/** {name} scenes */\n{COMMON_INCLUDES}\n{scenes}\n",
        encoding="utf-8",
        newline="\n",
    )

    ops = f"{energy}\n\n{gateway}\n\n{network}\n\n{points_block}\n"
    (out_dir / "pages_ops.c").write_text(
        f"/** {name} energy / gateway / network / points */\n{COMMON_INCLUDES}\n{ops}",
        encoding="utf-8",
        newline="\n",
    )

    life = f"{settings}\n\n{security_block}\n{schedule}\n\n{hvac}\n"
    (out_dir / "pages_life.c").write_text(
        f"/** {name} settings / security / schedule / hvac */\n{COMMON_INCLUDES}\n{life}",
        encoding="utf-8",
        newline="\n",
    )

    boot = f"""/** {name} boot */
{COMMON_INCLUDES}

void hub_theme_build(lv_obj_t *parent, hub_route_t route)
{{
    switch (route) {{
    case HUB_ROUTE_HOME: build_home(parent); break;
    case HUB_ROUTE_ROOM: build_room(parent); break;
    case HUB_ROUTE_SCENES: build_scenes(parent); break;
    case HUB_ROUTE_ENERGY: build_energy(parent); break;
    case HUB_ROUTE_GATEWAY: build_gateway(parent); break;
    case HUB_ROUTE_SETTINGS: build_settings(parent); break;
    case HUB_ROUTE_NETWORK: build_network(parent); break;
    case HUB_ROUTE_SECURITY: build_security(parent); break;
    case HUB_ROUTE_SCHEDULE: build_schedule(parent); break;
    case HUB_ROUTE_HVAC: build_hvac(parent); break;
    case HUB_ROUTE_POINTS: build_points(parent); break;
    default: build_home(parent); break;
    }}
}}

void app_ui_start(void)
{{
    hub_ui_init();
}}
"""
    (out_dir / "boot.c").write_text(boot, encoding="utf-8", newline="\n")

    # README for folder
    (out_dir / "README.md").write_text(
        f"""# {name} theme pack

Compile-time hub theme. Sources are theme-local (not shared with other themes).

| File | Role |
|------|------|
| `palette.c` | Colors / radius |
| `theme_local.h/.c` | Helpers, callbacks, `theme_card_chrome` |
| `home.c` | Home IA + bindings |
| `pages_room.c` | Room widgets (toggle / curtain / AC / fan) |
| `pages_scenes.c` | Scenes |
| `pages_ops.c` | Energy / gateway / network / points |
| `pages_life.c` | Settings / security / schedule / HVAC |
| `boot.c` | `hub_theme_build` + `app_ui_start` |

Select via `main/app_ui_theme_select.h` → `APP_UI_THEME_{tid.upper()}`.
""",
        encoding="utf-8",
        newline="\n",
    )

    pack.unlink()
    print(f"split {tid} → {out_dir} (deleted theme_pack.c)")


def main() -> None:
    # Add strip step to model before generating room that needs it
    issues = []
    for tid in THEME_IDS:
        try:
            write_theme(tid)
        except Exception as exc:  # noqa: BLE001
            issues.append(f"{tid}: {exc}")
            print(f"FAIL {tid}: {exc}", file=sys.stderr)
    if issues:
        sys.exit(1)
    print(f"done: {len(THEME_IDS)} theme folders")


if __name__ == "__main__":
    main()
